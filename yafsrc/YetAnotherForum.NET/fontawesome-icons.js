/**
 * Finds the Font Awesome icons used by YAF.NET and writes them to wwwroot/lib/_fontawesome-icons.scss,
 * only these icon classes are added to the css files (instead of all ~2600 icons, which were ~60% of forum.min.css).
 *
 * An icon counts as used if its name appears in the sources as "fa-name" or as a quoted string ("name" / 'name'),
 * e.g. icon="reply", Html.IconBadge("quote-left", "plus") or EventLogTypes.Error => "radiation".
 * That finds a few more icons than needed (e.g. a string "user" that is no icon), which is fine.
 *
 * Icons whose name is only built at runtime can't be found, add them to extraIcons / extraBrandIcons.
 *
 * Run with: grunt fontAwesomeIcons (part of the default task)
 */

const fs = require('fs');
const path = require('path');

/**
 * Icons that are used, but not found by the scan.
 */
const extraIcons = [];

/**
 * Brand icons that are used, but not found by the scan (the names of the bbcode extensions are added automatically,
 * see ForumEditorTagHelper: "fab fa-{name}").
 */
const extraBrandIcons = [];

const root = path.resolve(__dirname, '..');
const variablesFile = path.join(__dirname, 'node_modules', '@fortawesome', 'fontawesome-free', 'scss', '_variables.scss');
const outputFile = path.join(__dirname, 'wwwroot', 'lib', '_fontawesome-icons.scss');

const sourceExtensions = ['.cs', '.cshtml', '.ts', '.js', '.json', '.xml'];
const skipFolders = ['node_modules', 'bin', 'obj', '.git', '.vs', 'Tests', 'ServiceStack', 'docker', 'TestResults'];

/**
 * Reads the icon names of a map ($icons or $brand-icons) of the Font Awesome variables.
 */
function readIconMap(variables, mapName) {
    const start = variables.indexOf(`${mapName}: (`);

    if (start < 0) {
        throw new Error(`${mapName} not found in ${variablesFile}`);
    }

    const end = variables.indexOf(');', start);
    const names = new Set();

    for (const match of variables.substring(start, end).matchAll(/^\s*"([^"]+)":/gm)) {
        names.add(match[1]);
    }

    return names;
}

/**
 * All source files of the forum (C#, razor, typescript, built javascript incl. the vendor scripts, language and resource files).
 */
function* sourceFiles(folder) {
    for (const entry of fs.readdirSync(folder, { withFileTypes: true })) {
        const fullPath = path.join(folder, entry.name);

        if (entry.isDirectory()) {
            if (!skipFolders.includes(entry.name)) {
                yield* sourceFiles(fullPath);
            }
        } else if (sourceExtensions.includes(path.extname(entry.name)) && !entry.name.endsWith('.map')) {
            yield fullPath;
        }
    }
}

/**
 * Collects all words that may be an icon name.
 */
function collectCandidates() {
    const candidates = new Set();

    for (const file of sourceFiles(root)) {
        const content = fs.readFileSync(file, 'utf8');

        for (const match of content.matchAll(/fa-([a-z0-9]+(?:-[a-z0-9]+)*)/g)) {
            candidates.add(match[1]);
        }

        for (const match of content.matchAll(/["'`]([a-z0-9]+(?:-[a-z0-9]+)*)["'`]/g)) {
            candidates.add(match[1]);
        }
    }

    return candidates;
}

/**
 * The names of the bbcode extensions, the editor shows them as brand icon.
 */
function bbCodeExtensionNames() {
    const file = path.join(__dirname, 'wwwroot', 'resources', 'BBCodeExtensions.xml');

    return [...fs.readFileSync(file, 'utf8').matchAll(/<Name>([^<]+)<\/Name>/g)].map(m => m[1].trim().toLowerCase());
}

function scssList(name, icons) {
    return icons.length === 0
        ? `$${name}: ();\n`
        : `$${name}: (\n${icons.map(i => `    "${i}"`).join(',\n')}\n);\n`;
}

module.exports = function generateFontAwesomeIcons(log) {
    const variables = fs.readFileSync(variablesFile, 'utf8');
    const allIcons = readIconMap(variables, '$icons');
    const allBrandIcons = readIconMap(variables, '$brand-icons');

    const candidates = collectCandidates();

    for (const name of bbCodeExtensionNames()) {
        candidates.add(name);
    }

    for (const name of [...extraIcons, ...extraBrandIcons]) {
        candidates.add(name);
    }

    const icons = [...candidates].filter(c => allIcons.has(c)).sort();
    const brandIcons = [...candidates].filter(c => allBrandIcons.has(c)).sort();

    for (const name of extraIcons.filter(i => !allIcons.has(i))) {
        log(`warning: ${name} is no Font Awesome icon`);
    }

    for (const name of extraBrandIcons.filter(i => !allBrandIcons.has(i))) {
        log(`warning: ${name} is no Font Awesome brand icon`);
    }

    const content = `// generated by fontawesome-icons.js (grunt fontAwesomeIcons), don't edit\n// the Font Awesome icons used by the forum, only these icon classes are in the css files\n\n${
	    scssList('icons', icons)}\n${scssList('brand-icons', brandIcons)}`;

    fs.writeFileSync(outputFile, content);

    log(`${icons.length} of ${allIcons.size} icons and ${brandIcons.length} of ${allBrandIcons.size} brand icons are used`);
};
